MONO_HLSB = 0


class FrameBuffer:
    def __init__(self, buf, width, height, fmt):
        if fmt != MONO_HLSB:
            raise ValueError("only MONO_HLSB supported")
        self.buf = buf
        self.width = width
        self.height = height
        self._row = (width + 7) // 8

    def fill(self, c):
        v = 0xFF if c else 0x00
        for i in range(len(self.buf)):
            self.buf[i] = v

    def pixel(self, x, y, c=None):
        if x < 0 or y < 0 or x >= self.width or y >= self.height:
            return 0 if c is None else None
        i = y * self._row + (x >> 3)
        m = 0x80 >> (x & 7)
        if c is None:
            return 1 if (self.buf[i] & m) else 0
        if c:
            self.buf[i] |= m
        else:
            self.buf[i] &= ~m & 0xFF

    def fill_rect(self, x, y, w, h, c):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.pixel(xx, yy, c)

    def hline(self, x, y, w, c):
        self.fill_rect(x, y, w, 1, c)

    def vline(self, x, y, h, c):
        self.fill_rect(x, y, 1, h, c)

    def rect(self, x, y, w, h, c):
        self.hline(x, y, w, c)
        self.hline(x, y + h - 1, w, c)
        self.vline(x, y, h, c)
        self.vline(x + w - 1, y, h, c)

    def text(self, s, x, y, c=1):
        s = str(s)
        for i, ch in enumerate(s):
            o = ord(ch)
            if o < 32 or o > 127:
                o = 63  # ?
            base = (o - 32) * 8
            cx = x + i * 8
            for col in range(8):
                bits = _FONT[base + col]
                for row in range(8):
                    if bits & (1 << row):
                        self.pixel(cx + col, y + row, c)


class FakeEPD:
    def __init__(self, width=800, height=480):
        self.width = width
        self.height = height
        self.buffer_black = bytearray(height * width // 8)
        self.buffer_red = bytearray(height * width // 8)
        self.imageblack = FrameBuffer(self.buffer_black, width, height, MONO_HLSB)
        self.imagered = FrameBuffer(self.buffer_red, width, height, MONO_HLSB)


def _png_chunk(tag: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)


def write_png(path: Path, width: int, height: int, rgb: bytes) -> None:
    raw = bytearray()
    row = width * 3
    for y in range(height):
        raw.append(0)
        raw.extend(rgb[y * row : (y + 1) * row])
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n"
    png += _png_chunk(b"IHDR", ihdr)
    png += _png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += _png_chunk(b"IEND", b"")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def composite(epd: FakeEPD) -> bytes:
    """Black plane: 0=ink, 1=paper. Red plane: 1=red ink."""
    w, h = epd.width, epd.height
    out = bytearray(w * h * 3)
    row = (w + 7) // 8
    PAPER = (242, 236, 220)
    BLACK = (28, 28, 28)
    RED = (176, 28, 28)
    for y in range(h):
        for x in range(w):
            i = y * row + (x >> 3)
            m = 0x80 >> (x & 7)
            red = bool(epd.buffer_red[i] & m)
            black = not bool(epd.buffer_black[i] & m)
            if red:
                r, g, b = RED
            elif black:
                r, g, b = BLACK
            else:
                r, g, b = PAPER
            o = (y * w + x) * 3
            out[o], out[o + 1], out[o + 2] = r, g, b
    return bytes(out)


